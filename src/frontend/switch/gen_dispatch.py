#!/usr/bin/env python3
"""Generate DekoDispatch.h for nekoDS Switch frontend.

Reads C declarations from neko3d's deko3d.h and emits a dispatch struct +
dlsym loader for the dk* functions used by the ported deko3d GPU
(GPU2D_Deko/GPU3D_Deko/DekoContext/GpuMemHeap/...).

Usage (from this directory):
  python3 gen_dispatch.py [neko3d-include-dir] [output-header]
Defaults assume sibling checkouts: ../../SDL-dlink style layout, i.e.
  <root>/nekoDS, <root>/neko3d
"""
import os
import re
import sys

# Union of SDL-dlink's dispatch list and the extra fns the Deko GPU needs.
WANTED = """
dkCmdBufAddMemory
dkCmdBufBarrier
dkCmdBufBindBlendStates
dkCmdBufBindColorState
dkCmdBufBindColorWriteState
dkCmdBufBindDepthStencilState
dkCmdBufBindImageDescriptorSet
dkCmdBufBindImages
dkCmdBufBindIdxBuffer
dkCmdBufBindRasterizerState
dkCmdBufBindRenderTargets
dkCmdBufBindSamplerDescriptorSet
dkCmdBufBindShaders
dkCmdBufBindStorageBuffers
dkCmdBufBindTextures
dkCmdBufBindUniformBuffers
dkCmdBufBindVtxAttribState
dkCmdBufBindVtxBuffers
dkCmdBufBindVtxBufferState
dkCmdBufClear
dkCmdBufClearColor
dkCmdBufClearDepthStencil
dkCmdBufCopyBuffer
dkCmdBufCopyBufferToImage
dkCmdBufCopyImageToBuffer
dkCmdBufCreate
dkCmdBufDestroy
dkCmdBufDiscardColor
dkCmdBufDiscardDepthStencil
dkCmdBufDispatchCompute
dkCmdBufDispatchComputeIndirect
dkCmdBufDraw
dkCmdBufDrawIndexed
dkCmdBufFinishList
dkCmdBufPushConstants
dkCmdBufPushData
dkCmdBufSetScissors
dkCmdBufSetViewports
dkCmdBufSignalFence
dkCmdBufWaitFence
dkDeviceCreate
dkDeviceDestroy
dkFenceWait
dkImageDescriptorInitialize
dkImageInitialize
dkImageLayoutGetAlignment
dkImageLayoutGetSize
dkImageLayoutInitialize
dkMemBlockCreate
dkMemBlockDestroy
dkMemBlockGetCpuAddr
dkMemBlockGetGpuAddr
dkQueueAcquireImage
dkQueueCreate
dkQueueDestroy
dkQueueFlush
dkQueueIsInErrorState
dkQueuePresentImage
dkQueueSubmitCommands
dkQueueWaitIdle
dkSamplerDescriptorInitialize
dkShaderInitialize
dkShaderIsValid
dkSwapchainCreate
dkSwapchainDestroy
dkSwapchainSetCrop
""".split()


def parse_decls(header_path):
    text = open(header_path, encoding="utf-8").read()
    out = []
    buf = ""
    depth = 0
    for line in text.splitlines():
        s = line.strip()
        if not buf and not re.match(
            r"^(?:[\w:\*&<>\s]+?)\s+dk[A-Z]\w*\s*\(", s
        ):
            continue
        buf += " " + s
        depth += s.count("(") - s.count(")")
        if buf and depth <= 0 and ";" in s:
            out.append(buf.strip())
            buf = ""
            depth = 0
    decls = {}
    for d in out:
        m = re.match(r"^(.*?)\s+(dk[A-Z]\w*)\s*\((.*)\)\s*;\s*$", d, re.S)
        if m:
            decls[m.group(2)] = (m.group(1).strip(), m.group(3).strip())
    return decls


def arg_names(args):
    """Split a C parameter list and return [(type, name)] (name "" if none)."""
    args = args.strip()
    if args in ("", "void"):
        return []
    out = []
    for a in args.split(","):
        a = a.strip()
        m = re.match(r"^(.*[\*\s])(\w+)(\s*\[[^\]]*\])?$", a)
        if m:
            out.append((m.group(1).strip(), m.group(2)))
        else:
            out.append((a, ""))
    return out


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    inc = sys.argv[1] if len(sys.argv) > 1 else os.path.normpath(
        os.path.join(here, "..", "..", "..", "..", "neko3d", "include")
    )
    outpath = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        here, "DekoDispatch.h"
    )
    with open(os.path.join(inc, "deko3d.h"), encoding="utf-8") as f:
        header_text = f.read()
    use_extern_c = 'extern "C"' in header_text
    print("deko3d.h linkage:", "extern C" if use_extern_c else "C++")
    decls = parse_decls(os.path.join(inc, "deko3d.h"))
    missing = [w for w in WANTED if w not in decls]
    if missing:
        print("NOT FOUND in deko3d.h:", missing)
        sys.exit(1)
    for w in WANTED:
        if "..." in decls[w][1]:
            print("VARIADIC, unsupported:", w)
            sys.exit(1)
    with open(outpath, "w", encoding="utf-8", newline="") as f:
        f.write("// AUTO-GENERATED by gen_dispatch.py from neko3d include/deko3d.h\n")
        f.write("// Do not edit by hand; regenerate with:\n")
        f.write("//   python3 gen_dispatch.py [neko3d-include-dir] [output-header]\n")
        f.write("#ifndef NEKODS_DEKO_DISPATCH_H\n")
        f.write("#define NEKODS_DEKO_DISPATCH_H\n\n")
        f.write("#include <switch.h>\n")
        f.write("#include <dlink/dlink.h>\n\n")
        f.write("#include <deko3d.h>\n\n")
        f.write("// Loaded from neko3d.dnro at launch (see SwitchSDL.h GblNeko).\n")
        f.write("struct DekoDispatch\n{\n")
        for w in WANTED:
            ret, args = decls[w]
            if args == "void":
                f.write(f"    {ret} (*{w})(void);\n")
            else:
                f.write(f"    {ret} (*{w})({args});\n")
        f.write("};\n\n")
        f.write("extern DekoDispatch DekoDk;\n\n")
        f.write("// Binds every entry from a dlink neko3d handle. False on first miss.\n")
        f.write("inline bool DekoLoadDispatch(void* h)\n{\n")
        f.write("    if (!h) return false;\n")
        for w in WANTED:
            f.write(
                f'    DekoDk.{w} = reinterpret_cast<decltype(DekoDk.{w})>(dlsym(h, "{w}"));\n'
            )
            f.write(f"    if (!DekoDk.{w}) return false;\n")
        f.write("    return true;\n}\n\n")
        f.write("#endif\n")
    print(f"wrote {outpath} ({len(WANTED)} functions)")

    # Shim TU: real definitions with dk linkage that forward through the
    # table. deko3d.hpp's inline methods call ::dkFoo(...), which the
    # linker resolves to these; at runtime they land in neko3d.dnro.
    # (Object-like macros can't do this job: `::(DekoDk.dkFoo)(...)`
    # is not valid syntax.)
    shim_path = os.path.join(os.path.dirname(outpath), "DekoShim.cpp")
    with open(shim_path, "w", encoding="utf-8", newline="") as f:
        f.write("// AUTO-GENERATED by gen_dispatch.py — see DekoDispatch.h\n")
        f.write('#include "DekoDispatch.h"\n\n')
        if use_extern_c:
            f.write('extern "C" {\n\n')
        for w in WANTED:
            ret, args = decls[w]
            names = [n for _, n in arg_names(args) if n]
            call = ", ".join(names)
            if args.strip() == "void":
                f.write(f"{ret} {w}(void)\n{{\n")
            else:
                f.write(f"{ret} {w}({args})\n{{\n")
            if ret.strip() == "void":
                f.write(f"    DekoDk.{w}({call});\n")
            else:
                f.write(f"    return DekoDk.{w}({call});\n")
            f.write("}\n\n")
        if use_extern_c:
            f.write('} // extern "C"\n')
    print(f"wrote {shim_path}")

    # Companion header: pristine deko3d.h types plus the dispatch table,
    # then the C++ wrapper. dk:: inline methods call ::dkFoo(...), which
    # the linker resolves to the forwarding definitions in DekoShim.cpp.
    api_path = os.path.join(os.path.dirname(outpath), "DekoAPI.h")
    with open(api_path, "w", encoding="utf-8", newline="") as f:
        f.write("// AUTO-GENERATED by gen_dispatch.py — see DekoDispatch.h\n")
        f.write("#ifndef NEKODS_DEKO_API_H\n")
        f.write("#define NEKODS_DEKO_API_H\n\n")
        f.write("#include <switch.h>\n")
        f.write("#include <dlink/dlink.h>\n\n")
        f.write("// 1. pristine C declarations, types and DK_* macros\n")
        f.write("#include <deko3d.h>\n\n")
        f.write("// 2. dispatch table (needs the types above)\n")
        f.write('#include "DekoDispatch.h"\n\n')
        f.write("// 3. C++ wrapper; its ::dkFoo calls link against DekoShim.cpp\n")
        f.write("#include <deko3d.hpp>\n\n")
        f.write("#endif\n")
    print(f"wrote {api_path}")


main()
